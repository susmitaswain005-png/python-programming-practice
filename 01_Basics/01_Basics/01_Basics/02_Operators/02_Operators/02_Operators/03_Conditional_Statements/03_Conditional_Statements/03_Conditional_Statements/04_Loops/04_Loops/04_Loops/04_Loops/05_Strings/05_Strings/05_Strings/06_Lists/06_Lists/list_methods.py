fruits = ["Apple", "Mango", "Banana"]

# Add an element
fruits.append("Orange")
print(fruits)

# Insert an element
fruits.insert(1, "Grapes")
print(fruits)

# Remove an element
fruits.remove("Mango")
print(fruits)

# Remove the last element
fruits.pop()
print(fruits)

# Sort the list
fruits.sort()
print(fruits)

# Reverse the list
fruits.reverse()
print(fruits)
